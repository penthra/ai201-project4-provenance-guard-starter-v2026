"""
Turning two numbers into one, and one number into something a person can read.
← YOU BUILD THIS IN MILESTONES 4 AND 5

The combining rule and reader-facing label mapping are implemented.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` is where you stop writing for a machine and start writing for
a person. A score of 0.62 means nothing to a writer.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """Combine two 0–1 AI-likeness scores using configured weights.

    The documented rule is 0.5 * model_score + 0.5 * style_score.
    Weights live in config.py and must be nonnegative and sum to 1.
    Equal weighting gives neither heuristic priority. Disagreement is handled
    by averaging: 0.9 and 0.1 give 0.5, inside the configured unsure band.
    Thresholds are applied separately by score_to_label, not here.
    """
    model_contribution = config.WEIGHT_MODEL_SIGNAL * model_score
    style_contribution = config.WEIGHT_STYLE_SIGNAL * style_score
    return model_contribution + style_contribution



def score_to_label(score: float) -> tuple[str, str]:
    """Return the machine-readable guess and exact README reader message.

    Human includes the lower boundary, AI includes the upper boundary, and
    every score strictly between them is unsure. Boundaries live in config.py.
    """
    if score >= config.AI_THRESHOLD:
        return "ai", (
            "We think this text may have been generated by AI. "
            "This estimate can be wrong. You can request a review."
        )
    if score <= config.HUMAN_THRESHOLD:
        return "human", (
            "We think this text was probably written by a person. "
            "This is an automated estimate and can be wrong."
        )
    return "unsure", (
        "Our checks cannot reliably tell whether this text was written "
        "by a person or generated by AI."
    )


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("human", f"0.00 <= score <= {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} < score < {config.AI_THRESHOLD:.2f}"),
        ("ai", f"{config.AI_THRESHOLD:.2f} <= score <= 1.00"),
    ]
