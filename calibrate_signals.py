"""Score four sourced calibration pieces through /submit and verify audit readback.

Run with the project's environment: python calibrate_signals.py
Each run appends four real decisions to logs/audit.jsonl.
"""
import json
from pathlib import Path

from app import app
import audit
import scoring

AI_TEXT = (
    'Effective time management helps students complete their work and reduce stress. '
    'A clear schedule allows students to organize their tasks and set realistic goals. '
    'Regular breaks help students maintain focus throughout the day. '
    'By reviewing their progress, students can adjust their plans and improve their results.'
)
EDITED_AI_TEXT = AI_TEXT.replace('A clear schedule', 'A simple schedule').replace(
    'Regular breaks help students maintain focus throughout the day.',
    'Short breaks help students stay focused. I find that useful, too.'
)
CASES = [
    {
        'name': 'Clearly AI', 'expected_origin': 'ai',
        'provenance': 'Generated by the assistant for this calibration run.',
        'text': AI_TEXT,
    },
    {
        'name': 'Clearly human', 'expected_origin': 'human',
        'provenance': 'Mark Twain, The Adventures of Tom Sawyer, Chapter II, opening four sentences (public domain).',
        'source': 'https://www.gutenberg.org/files/74/74-h/74-h.htm',
        'text': (
            'Saturday morning was come, and all the summer world was bright and fresh, and brimming with life. '
            'There was a song in every heart; and if the heart was young the music issued at the lips. '
            'There was cheer in every face and a spring in every step. '
            'The locust-trees were in bloom and the fragrance of the blossoms filled the air.'
        ),
    },
    {
        'name': 'Formal human', 'expected_origin': 'human',
        'provenance': "Abraham Lincoln, Second Inaugural Address, opening three sentences (public domain; NPS transcription).",
        'source': 'https://www.nps.gov/linc/learn/historyculture/lincoln-second-inaugural.htm',
        'text': (
            'Fellow countrymen: at this second appearing to take the oath of the presidential office there is less occasion for an extended address than there was at the first. '
            'Then a statement somewhat in detail of a course to be pursued seemed fitting and proper. '
            'Now, at the expiration of four years during which public declarations have been constantly called forth on every point and phase of the great contest which still absorbs the attention and engrosses the energies of the nation little that is new could be presented.'
        ),
    },
    {
        'name': 'Lightly-edited AI', 'expected_origin': 'ai',
        'provenance': 'Assistant edited the Clearly AI passage: two word substitutions and one sentence split with a personal aside. This is a simulated edit, not a human editing trial.',
        'text': EDITED_AI_TEXT,
    },
]


def main():
    client = app.test_client()
    results = []
    for index, case in enumerate(CASES, 1):
        response = client.post('/submit', json={
            'text': case['text'], 'creator_id': f'calibration-{index}',
        })
        if response.status_code != 200:
            raise RuntimeError(f"{case['name']}: HTTP {response.status_code}: {response.get_json()}")
        body = response.get_json()
        entry, = audit.entries_for(body['content_id'])
        for key in ('model_score', 'style_score'):
            assert body[key] == entry[key]
        assert body['confidence'] == entry['combined_score']
        assert entry['status'] == 'decided'
        assert (body['guess'], body['label']) == scoring.score_to_label(body['confidence'])
        assert entry['guess'] == body['guess'] and entry['label'] == body['label']
        log_response = client.get('/log').get_json()
        assert entry in log_response['entries']
        row = dict(case, **body, combined_score=body['confidence'],
                   mapped_guess=scoring.score_to_label(body['confidence'])[0])
        results.append(row)
        print(f"{case['name']}: model={body['model_score']:.4f}, "
              f"style={body['style_score']:.4f}, combined={body['confidence']:.4f}, "
              f"mapped_guess={row['mapped_guess']}, log_verified=True", flush=True)
    output = Path(__file__).resolve().parent / 'results' / 'calibration_signals.json'
    output.write_text(json.dumps(results, indent=2) + '\n', encoding='utf-8')
    print(f'Saved {output}')
    print('Verified: response and audit guess/label match score_to_label.')


if __name__ == '__main__':
    main()
